#!/usr/bin/env python3.12
"""Write the leaderboard from the two v2 result tables: the summary (one
regression and one classification table) into README.md, between the
LEADERBOARD markers, and the full per-forecast-length tables into
results/LEADERBOARD.md.

Run from anywhere:  python3.12 scripts/make_leaderboard.py
Other inputs:       --regression CSV  --event CSV  --readme MD  --full MD
"""
import argparse
import sys
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
if str(REPO) not in sys.path:    # run as a plain script from any folder
    sys.path.insert(0, str(REPO))

from tslib.benchmark.leaderboard import leaderboard_markdown, summary_html  # noqa: E402

START, END = "<!-- LEADERBOARD:START -->", "<!-- LEADERBOARD:END -->"
SUMMARY_INTRO = (
    "_Representative scores of the univariate tracks. Each cell is the mean over "
    "the 5 folds and the 3 input lengths (1, 3 and 7 days) at one forecast length; "
    "forecast lengths are never averaged together. The best model of each column "
    "is in bold._")
SUMMARY_OUTRO = (
    "**Full performance tables** — every metric (RMSE, MSA, logR, HSS, TSS), "
    "the multivariate track and one table per forecast length — are in "
    "[`results/LEADERBOARD.md`](results/LEADERBOARD.md). Per-run values: "
    "[`results/results_regression.csv`](results/results_regression.csv), "
    "[`results/results_event.csv`](results/results_event.csv).")
FULL_HEADER = (
    "# Full benchmark tables\n\n"
    "<!-- Generated by scripts/make_leaderboard.py from results/results_regression.csv "
    "and results/results_event.csv; do not edit by hand. -->\n\n"
    "One section per forecast length (3 h, 6 h, 12 h, 24 h) and one table per track. "
    "Each cell is the mean of a model's runs at that forecast length over the 5 folds "
    "and the 3 input lengths (1-day, 3-day and 7-day look-back, seq_len 288, 864 and "
    "2016); forecast lengths are never averaged together. Runs with an undefined value "
    "are left out of the mean. `k/n` marks a cell where only k of the n runs of that "
    "forecast length (folds x input lengths) have a value, and † marks a model with "
    "fewer runs than that, whose rows are not directly comparable with the others (see "
    "the note under the section). RMSE (log10 flux) and MSA (median symmetric accuracy, "
    "%) are better lower; logR (correlation of the log10 values), HSS and TSS are "
    "better higher. HSS and TSS are per-day scores (one forecast per 24 h) at the "
    "M-class (SXR) and 10 pfu (proton) thresholds. Rows are ordered by the first "
    "channel's RMSE. Per-run results: [`results_regression.csv`](results_regression.csv), "
    "[`results_event.csv`](results_event.csv). Definitions: "
    "[`docs/metrics.md`](../docs/metrics.md).")


def parse_args(argv=None):
    p = argparse.ArgumentParser(
        description="Write the leaderboard summary into README.md and the full "
                    "tables into results/LEADERBOARD.md.")
    p.add_argument("--regression", type=Path, default=REPO / "results" / "results_regression.csv",
                   metavar="CSV", help="regression result table (default: %(default)s)")
    p.add_argument("--event", type=Path, default=REPO / "results" / "results_event.csv",
                   metavar="CSV", help="event result table (default: %(default)s)")
    p.add_argument("--readme", type=Path, default=REPO / "README.md",
                   metavar="MD", help="file with the LEADERBOARD markers (default: %(default)s)")
    p.add_argument("--full", type=Path, default=REPO / "results" / "LEADERBOARD.md",
                   metavar="MD", help="full tables, rewritten as a whole (default: %(default)s)")
    return p.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)
    for path in (args.regression, args.event, args.readme):
        if not path.is_file():
            print(f"error: {path} is not a file", file=sys.stderr)
            return 1
    text = args.readme.read_text(encoding="utf-8")
    if START not in text or END not in text:
        print(f"error: {args.readme} has no {START} ... {END} block", file=sys.stderr)
        return 1
    reg, evt = pd.read_csv(args.regression), pd.read_csv(args.event)
    pre, rest = text.split(START, 1)
    _, post = rest.split(END, 1)
    summary = f"{SUMMARY_INTRO}\n\n{summary_html(reg, evt)}\n\n{SUMMARY_OUTRO}"
    args.readme.write_text(f"{pre}{START}\n\n{summary}\n\n{END}{post}", encoding="utf-8")
    args.full.parent.mkdir(parents=True, exist_ok=True)
    args.full.write_text(f"{FULL_HEADER}\n\n{leaderboard_markdown(reg, evt)}\n",
                         encoding="utf-8")
    print(f"leaderboard summary written to {args.readme}; full tables to {args.full}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
